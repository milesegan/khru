import type { StudyEntry } from "../types";
import { AGE_VOCABULARY } from "./age-levels";

const WORD_AGE_CATEGORIES = new Map(
  Object.entries(AGE_VOCABULARY).flatMap(([category, vocabulary]) =>
    vocabulary.map((thai) => [thai, category] as const),
  ),
);

// Each spelling appears once in its age list, even when the main deck has
// separate cards for different meanings or uses of the same word.
const AGE_WORD_VARIANTS: Record<string, string> = {
  ตา: "taa-eye",
  เย็น: "yen",
  ปิด: "pit",
  เปิด: "poet",
};

const word = (
  id: string,
  thai: string,
  transliteration: string,
  meaning: string,
  note: string,
  difficulty: 1 | 2 | 3 | 4 | 5,
  tags: string[],
): StudyEntry => {
  const variantId = AGE_WORD_VARIANTS[thai];
  const ageCategory =
    !variantId || variantId === id ? WORD_AGE_CATEGORIES.get(thai) : undefined;

  return {
    id,
    thai,
    transliteration,
    meaning,
    note,
    difficulty,
    tags: ageCategory ? [...tags, ageCategory] : tags,
  };
};

